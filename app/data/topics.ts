export type TopicDifficulty = "warm-up" | "stretch" | "pressure";

export type TopicCategory =
  | "Tech"
  | "Finance"
  | "Hot takes"
  | "Storytelling"
  | "Debate"
  | "General";

export type SpeechTopic = {
  id: string;
  prompt: string;
  category: TopicCategory;
  difficulty: TopicDifficulty;
  trains: string;
  why: string;
  framework: string;
  timeSeconds: number;
  tags: string[];
};

function topic(
  id: string,
  prompt: string,
  category: TopicCategory,
  difficulty: TopicDifficulty,
  trains: string,
  why: string,
  framework: string,
  tags: string[],
): SpeechTopic {
  const timeSeconds =
    difficulty === "warm-up" ? 75 : difficulty === "stretch" ? 90 : 105;

  return { id, prompt, category, difficulty, trains, why, framework, timeSeconds, tags };
}

